//! Audio duration without a full decode - ID3/MP4/FLAC tag *metadata* doesn't reliably carry this (ID3v2's TLEN frame is
//! optional and rarely set by real encoders), so this reads each container format's own structural header instead:
//! FLAC's STREAMINFO and MP4's mvhd give an exact sample count/timescale; MP3 either has a Xing/VBRI frame-count header
//! (most real-world VBR rips do, from LAME/etc.) or falls back to a bitrate-based estimate from the first frame plus the
//! file's total size. Deliberately NOT a full decode - every parser here only reads `prefix`, a bounded byte range from
//! the START of the file (see [`DURATION_PREFIX_BYTES`]), never the whole thing. A format whose duration genuinely
//! isn't derivable from a prefix (MP4 with its `moov` box placed at the end - an un-"faststart"-optimized file) returns
//! `None` rather than reading further.
//!
//! Port of `packages/core/src/metadata/parseDuration.ts`, kept byte-for-byte compatible: the TypeScript reads a byte
//! past the end of the buffer as `undefined`, which its bit operations turn into 0, so a truncated header parses as if
//! zero-padded instead of failing. [`byte`] reproduces that. `tests/duration_golden.rs` checks this port against vectors
//! generated by the TypeScript itself.

/// How much of the file's start [`parse_duration_seconds`] ever looks at - generous enough for a large ID3v2 tag
/// (embedded cover art can run to hundreds of KB) plus whatever container header follows it, while still being a small
/// fraction of a real audio file.
pub const DURATION_PREFIX_BYTES: usize = 512 * 1024;

/// Upper bound for a widened prefix: a bigger ID3 tag than this (absurd even for embedded art) is left to a fallback
/// duration source.
pub const MAX_DURATION_PREFIX_BYTES: usize = 16 * 1024 * 1024;

/// Room after an ID3v2 tag for the first MPEG frame header and its Xing/VBRI header.
const MP3_FRAME_WINDOW_BYTES: usize = 64 * 1024;

fn ext_of(file_name: &str) -> String {
    match file_name.rfind('.') {
        None => String::new(),
        Some(dot) => file_name[dot + 1..].to_lowercase(),
    }
}

/// `bytes[i]` with JavaScript's out-of-range behaviour (an `undefined` that bit operations treat as 0).
fn byte(bytes: &[u8], i: usize) -> u8 {
    bytes.get(i).copied().unwrap_or(0)
}

fn read_u32_be(bytes: &[u8], offset: usize) -> u32 {
    u32::from_be_bytes([byte(bytes, offset), byte(bytes, offset + 1), byte(bytes, offset + 2), byte(bytes, offset + 3)])
}

fn read_u32_le(bytes: &[u8], offset: usize) -> u32 {
    u32::from_le_bytes([byte(bytes, offset), byte(bytes, offset + 1), byte(bytes, offset + 2), byte(bytes, offset + 3)])
}

fn matches_ascii(bytes: &[u8], offset: usize, text: &str) -> bool {
    bytes.get(offset..offset + text.len()).is_some_and(|b| b == text.as_bytes())
}

// ---------------------------------------------------------------------
// FLAC - "fLaC" then a METADATA_BLOCK_STREAMINFO (34 bytes, right after a 4-byte block header) with sample rate (20
// bits) and total sample count (36 bits) packed into one 64-bit big-endian span. Always near the very start of the
// file, well within any reasonable prefix.
// ---------------------------------------------------------------------
fn parse_flac_duration(bytes: &[u8]) -> Option<f64> {
    if !matches_ascii(bytes, 0, "fLaC") || bytes.len() < 8 + 18 {
        return None;
    }
    // Block header: byte 4 = (last-block flag << 7) | block type; type 0 is STREAMINFO, which the FLAC spec requires
    // to be the very first block.
    if bytes[4] & 0x7f != 0 {
        return None;
    }
    // The 8-byte span at offset 18 holds sampleRate(20) | channels-1(3) | bitsPerSample-1(5) | totalSamples(36).
    let packed = u64::from_be_bytes(bytes[18..26].try_into().ok()?);
    let sample_rate = (packed >> 44) & 0xf_ffff;
    let total_samples = packed & 0xf_ffff_ffff;
    if sample_rate == 0 {
        return None;
    }
    Some(total_samples as f64 / sample_rate as f64)
}

// ---------------------------------------------------------------------
// WAV - a RIFF/WAVE container of flat chunks; "fmt " gives the byte rate, "data" gives the payload size. Both chunks
// are conventionally early in the file (well before any audio payload), so a bounded prefix scan is safe.
// ---------------------------------------------------------------------
fn parse_wav_duration(bytes: &[u8]) -> Option<f64> {
    if !matches_ascii(bytes, 0, "RIFF") || !matches_ascii(bytes, 8, "WAVE") {
        return None;
    }
    let mut offset: u64 = 12;
    let mut byte_rate: Option<u32> = None;
    let mut data_size: Option<u32> = None;
    while offset + 8 <= bytes.len() as u64 && (byte_rate.is_none() || data_size.is_none()) {
        let at = offset as usize;
        let chunk_id = &bytes[at..at + 4];
        let chunk_size = read_u32_le(bytes, at + 4);
        if chunk_id == b"fmt " && offset + 8 + 16 <= bytes.len() as u64 {
            byte_rate = Some(read_u32_le(bytes, at + 8 + 8));
        } else if chunk_id == b"data" {
            data_size = Some(chunk_size);
        }
        // chunks are word-aligned - an odd size has a padding byte
        offset += 8 + chunk_size as u64 + (chunk_size % 2) as u64;
    }
    match (byte_rate, data_size) {
        (Some(rate), Some(size)) if rate != 0 => Some(size as f64 / rate as f64),
        _ => None,
    }
}

// ---------------------------------------------------------------------
// MP4/M4A/AAC (ISO base media format) - a tree of size-prefixed boxes; duration lives in "moov" > "mvhd". moov is
// conventionally near the start for a properly "faststart"-optimized file, but a file muxed with moov trailing after
// a large mdat has its duration outside any reasonable prefix - returns None there rather than reading further.
// ---------------------------------------------------------------------
struct BoxRange {
    start: i64,
    end: i64,
}

fn find_mp4_box(bytes: &[u8], kind: &[u8; 4], start: i64, end: i64) -> Option<BoxRange> {
    let mut offset = start;
    while offset + 8 <= end {
        let at = offset as usize;
        let mut size = read_u32_be(bytes, at) as i64;
        let mut header_size = 8;
        if size == 1 {
            // 64-bit extended size, stored right after the 4-byte type
            if offset + 16 > end {
                return None;
            }
            let high = read_u32_be(bytes, at + 8) as u64;
            let low = read_u32_be(bytes, at + 12) as u64;
            // JS computes this in f64, which is exact below 2^53; saturate rather than wrap above that.
            size = i64::try_from(high << 32 | low).unwrap_or(i64::MAX / 4);
            header_size = 16;
        } else if size == 0 {
            // "extends to end of file" - unbounded, nothing more to scan usefully.
            size = end - offset;
        }
        let box_type = [byte(bytes, at + 4), byte(bytes, at + 5), byte(bytes, at + 6), byte(bytes, at + 7)];
        if &box_type == kind {
            return Some(BoxRange { start: offset + header_size, end: (offset + size).min(end) });
        }
        if size < header_size {
            return None; // malformed - bail rather than loop forever
        }
        offset += size;
    }
    None
}

fn parse_mp4_duration(bytes: &[u8]) -> Option<f64> {
    let moov = find_mp4_box(bytes, b"moov", 0, bytes.len() as i64)?;
    let mvhd = find_mp4_box(bytes, b"mvhd", moov.start, moov.end)?;
    if mvhd.end - mvhd.start < 4 {
        return None;
    }
    let s = mvhd.start as usize;
    let version = byte(bytes, s);
    if version == 1 {
        if mvhd.end - mvhd.start < 4 + 8 + 8 + 4 + 8 {
            return None;
        }
        let timescale_offset = s + 4 + 8 + 8;
        let timescale = read_u32_be(bytes, timescale_offset);
        let duration = (read_u32_be(bytes, timescale_offset + 4) as u64) << 32 | read_u32_be(bytes, timescale_offset + 8) as u64;
        if timescale == 0 {
            return None;
        }
        return Some(duration as f64 / timescale as f64);
    }
    // version 0: 4 (version+flags) + 4 (creation) + 4 (modification) + 4 (timescale) + 4 (duration), all 32-bit
    if mvhd.end - mvhd.start < 4 + 4 + 4 + 4 + 4 {
        return None;
    }
    let timescale_offset = s + 4 + 4 + 4;
    let timescale = read_u32_be(bytes, timescale_offset);
    let duration = read_u32_be(bytes, timescale_offset + 4);
    if timescale == 0 {
        return None;
    }
    Some(duration as f64 / timescale as f64)
}

// ---------------------------------------------------------------------
// MP3 - skip any leading ID3v2 tag, find the first valid MPEG audio frame sync, and either read a Xing/Info (LAME and
// most other VBR encoders) or VBRI (Fraunhofer) header for an exact frame count, or fall back to a bitrate-based
// estimate from that one frame's header plus the file's total size (accurate for CBR, a reasonable approximation
// otherwise - there's no way to do better without scanning every frame).
// ---------------------------------------------------------------------

/// Sample rates by `[version bits][index]`; version bits 0b00 = MPEG2.5, 0b10 = MPEG2, 0b11 = MPEG1 (0b01 reserved).
fn mpeg_sample_rate(version_bits: u8, index: u8) -> u32 {
    let table: [u32; 4] = match version_bits {
        0b00 => [11025, 12000, 8000, 0],
        0b10 => [22050, 24000, 16000, 0],
        0b11 => [44100, 48000, 32000, 0],
        _ => return 0,
    };
    table[index as usize]
}

/// Bitrate in kbps by layer bits (1 = Layer3, 2 = Layer2, 3 = Layer1 - frame header numbering) and index. MPEG1 table
/// for MPEG1, otherwise the MPEG2/2.5 table, which covers Layer2/Layer3 only (Layer1 is vanishingly rare for music
/// files and falls through to "no frame here", as in the TypeScript). 0 means "no entry".
fn mpeg_bitrate_kbps(version_bits: u8, layer_bits: u8, index: u8) -> u32 {
    const V1_L1: [u32; 15] = [0, 32, 64, 96, 128, 160, 192, 224, 256, 288, 320, 352, 384, 416, 448];
    const V1_L2: [u32; 15] = [0, 32, 48, 56, 64, 80, 96, 112, 128, 160, 192, 224, 256, 320, 384];
    const V1_L3: [u32; 15] = [0, 32, 40, 48, 56, 64, 80, 96, 112, 128, 160, 192, 224, 256, 320];
    const V2: [u32; 15] = [0, 8, 16, 24, 32, 40, 48, 56, 64, 80, 96, 112, 128, 144, 160];
    let table: &[u32; 15] = match (version_bits == 0b11, layer_bits) {
        (true, 3) => &V1_L1,
        (true, 2) => &V1_L2,
        (true, 1) => &V1_L3,
        (false, 2) | (false, 1) => &V2,
        _ => return 0,
    };
    table[index as usize]
}

fn id3v2_tag_size(bytes: &[u8]) -> usize {
    if !matches_ascii(bytes, 0, "ID3") || bytes.len() < 10 {
        return 0;
    }
    // Synchsafe: 4 bytes, only the low 7 bits of each are significant.
    let size = ((bytes[6] as usize & 0x7f) << 21) | ((bytes[7] as usize & 0x7f) << 14) | ((bytes[8] as usize & 0x7f) << 7) | (bytes[9] as usize & 0x7f);
    10 + size
}

struct Mp3Frame {
    offset: usize,
    mpeg_version_bits: u8,
    layer_bits: u8,
    bitrate_kbps: u32,
    sample_rate: u32,
    channel_mode_bits: u8,
}

/// The first valid-looking MPEG audio frame header at or after `from`, or `None` if none is found within `bytes`.
fn find_mp3_frame_header(bytes: &[u8], from: usize) -> Option<Mp3Frame> {
    let mut offset = from;
    while offset + 4 <= bytes.len() {
        let here = offset;
        offset += 1;
        if bytes[here] != 0xff || bytes[here + 1] & 0xe0 != 0xe0 {
            continue;
        }
        let (b1, b2, b3) = (bytes[here + 1], bytes[here + 2], bytes[here + 3]);
        let mpeg_version_bits = (b1 >> 3) & 0b11;
        let layer_bits = (b1 >> 1) & 0b11;
        if mpeg_version_bits == 0b01 || layer_bits == 0b00 {
            continue; // reserved version/layer
        }
        let bitrate_index = (b2 >> 4) & 0x0f;
        let sample_rate_index = (b2 >> 2) & 0x03;
        if bitrate_index == 0 || bitrate_index == 0x0f || sample_rate_index == 3 {
            continue; // free/bad bitrate, reserved sample rate
        }
        let sample_rate = mpeg_sample_rate(mpeg_version_bits, sample_rate_index);
        if sample_rate == 0 {
            continue;
        }
        let bitrate_kbps = mpeg_bitrate_kbps(mpeg_version_bits, layer_bits, bitrate_index);
        if bitrate_kbps == 0 {
            continue;
        }
        return Some(Mp3Frame { offset: here, mpeg_version_bits, layer_bits, bitrate_kbps, sample_rate, channel_mode_bits: (b3 >> 6) & 0x03 });
    }
    None
}

fn samples_per_frame(mpeg_version_bits: u8, layer_bits: u8) -> u32 {
    match layer_bits {
        0b11 => 384,                                  // Layer1
        0b10 => 1152,                                 // Layer2
        _ if mpeg_version_bits == 0b11 => 1152,       // Layer3, MPEG1
        _ => 576,                                     // Layer3, MPEG2/2.5
    }
}

fn parse_mp3_duration(bytes: &[u8], total_size_bytes: u64) -> Option<f64> {
    let tag_size = id3v2_tag_size(bytes);
    let frame = find_mp3_frame_header(bytes, tag_size)?;

    let is_mpeg1 = frame.mpeg_version_bits == 0b11;
    let is_mono = frame.channel_mode_bits == 0b11;
    // Xing/Info sits after the side-info block, whose size depends on MPEG version and channel mode.
    let xing_offset = frame.offset + 4 + if is_mpeg1 { if is_mono { 17 } else { 32 } } else if is_mono { 9 } else { 17 };
    if (matches_ascii(bytes, xing_offset, "Xing") || matches_ascii(bytes, xing_offset, "Info")) && xing_offset + 8 <= bytes.len() {
        let flags = read_u32_be(bytes, xing_offset + 4);
        if flags & 0x1 != 0 {
            // "frames" field present, right after the 8-byte tag+flags.
            let frame_count = read_u32_be(bytes, xing_offset + 8);
            let spf = samples_per_frame(frame.mpeg_version_bits, frame.layer_bits);
            return Some(frame_count as f64 * spf as f64 / frame.sample_rate as f64);
        }
    }
    // VBRI (Fraunhofer encoder) - always exactly 32 bytes after the frame's own 4-byte header, regardless of
    // side-info size.
    let vbri_offset = frame.offset + 4 + 32;
    if matches_ascii(bytes, vbri_offset, "VBRI") && vbri_offset + 26 <= bytes.len() {
        let frame_count = read_u32_be(bytes, vbri_offset + 14);
        let spf = samples_per_frame(frame.mpeg_version_bits, frame.layer_bits);
        return Some(frame_count as f64 * spf as f64 / frame.sample_rate as f64);
    }
    // No VBR header - assume CBR and estimate from this frame's bitrate against the audio payload size (total file size
    // minus any ID3v2 header). ID3v1/APEv2 footers (128/32 bytes) are a rounding error against a real audio file's
    // size, so they're not worth accounting for.
    let audio_bytes = total_size_bytes as f64 - tag_size as f64;
    if audio_bytes <= 0.0 {
        return None;
    }
    Some(audio_bytes * 8.0 / (frame.bitrate_kbps as f64 * 1000.0))
}

/// How many leading bytes [`parse_duration_seconds`] needs for this file. Usually [`DURATION_PREFIX_BYTES`], but an MP3
/// whose ID3v2 tag is bigger than that (a large embedded cover easily is - real example: a 7 MB track with an 840 KB
/// tag) has its first audio frame, and so its Xing header, beyond the default prefix, which used to make the duration
/// come out as `None`. `prefix` only needs to hold the tag's 10-byte header.
pub fn duration_prefix_bytes_needed(prefix: &[u8], file_name: &str) -> usize {
    if ext_of(file_name) != "mp3" {
        return DURATION_PREFIX_BYTES;
    }
    let needed = id3v2_tag_size(prefix) + MP3_FRAME_WINDOW_BYTES;
    needed.max(DURATION_PREFIX_BYTES).min(MAX_DURATION_PREFIX_BYTES)
}

/// Dispatches to the right container parser by file extension. `prefix` should be up to [`DURATION_PREFIX_BYTES`] (or
/// [`duration_prefix_bytes_needed`]) from the START of the file; `total_size_bytes` is the file's real full size (used
/// only by MP3's bitrate-estimate fallback). Returns `None` for an unrecognized extension, a format not covered here
/// (OGG/Opus/WMA - their duration lives at the END of the file, not derivable from a prefix without a much larger
/// read), or a file this couldn't confidently parse.
pub fn parse_duration_seconds(prefix: &[u8], file_name: &str, total_size_bytes: u64) -> Option<f64> {
    match ext_of(file_name).as_str() {
        "flac" => parse_flac_duration(prefix),
        "wav" => parse_wav_duration(prefix),
        "m4a" | "mp4" | "aac" => parse_mp4_duration(prefix),
        "mp3" => parse_mp3_duration(prefix, total_size_bytes),
        _ => None,
    }
}

