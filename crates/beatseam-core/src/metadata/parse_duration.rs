    #[test]
    fn returns_none_for_an_unrecognized_extension() {
        assert_eq!(parse_duration_seconds(&[1, 2, 3], "song.ogg", 3), None);
    }

    #[test]
    fn returns_none_instead_of_failing_for_a_truncated_or_malformed_prefix() {
        assert_eq!(parse_duration_seconds(&[0x66, 0x4c, 0x61, 0x43], "song.flac", 4), None);
        assert_eq!(parse_duration_seconds(&[0xff, 0xfb], "song.mp3", 2), None);
    }

    // ---- shapes the TS tests don't cover (also covered by the golden vectors) ----

    #[test]
    fn wav_chunks_with_an_odd_size_are_padded_to_a_word_boundary() {
        // An odd-sized "LIST" chunk before "fmt " pushes everything by size + 1 padding byte.
        let wav = build_wav(8000, 1, 8, 8000);
        let list = cat(&[&ascii("LIST"), &3u32.to_le_bytes(), &[1, 2, 3, 0]]);
        let bytes = cat(&[&wav[..12], &list, &wav[12..]]);
        near(parse_duration_seconds(&bytes, "x.wav", bytes.len() as u64), 1.0, 1e-9);
    }

    #[test]
    fn mp4_with_a_64_bit_box_size_before_moov_is_skipped_correctly() {
        let moov = build_mp4(1000, 5000)[12..].to_vec(); // drop ftyp
        let big_len = 16 + 4u64;
        let big = cat(&[&1u32.to_be_bytes(), &ascii("free"), &big_len.to_be_bytes(), &[9, 9, 9, 9]]);
        let bytes = cat(&[&big, &moov]);
        near(parse_duration_seconds(&bytes, "x.mp4", bytes.len() as u64), 5.0, 1e-9);
    }

    #[test]
    fn mpeg2_layer3_stereo_uses_the_mpeg2_tables_and_576_samples_per_frame() {
        // MPEG2 (version bits 10), Layer3 (01), no CRC => byte1 = 111 10 01 1 = 0xf3; bitrate idx 8 = 64 kbps, 22050 Hz.
        let header = [0xff, 0xf3, 0x80, 0x00]; // stereo: channel mode 00, so Xing sits at 4 + 17
        let bytes = cat(&[&header, &[0; 17], &ascii("Info"), &1u32.to_be_bytes(), &1000u32.to_be_bytes(), &[0; 32]]);
        near(parse_duration_seconds(&bytes, "x.mp3", bytes.len() as u64), 1000.0 * 576.0 / 22050.0, 1e-9);
    }

    #[test]
    fn a_vbri_header_is_read_32_bytes_after_the_frame_header() {
        let header = [0xff, 0xfb, 0x90, 0x00]; // MPEG1 L3, 128 kbps, 44.1 kHz, stereo
        let mut bytes = cat(&[&header, &[0; 32], &ascii("VBRI"), &[0; 60]]);
        bytes[36 + 14..36 + 18].copy_from_slice(&2000u32.to_be_bytes());
        near(parse_duration_seconds(&bytes, "x.mp3", bytes.len() as u64), 2000.0 * 1152.0 / 44100.0, 1e-9);
    }

    #[test]
    fn a_header_cut_off_mid_field_reads_the_missing_bytes_as_zero_like_the_ts() {
        // Xing flags say "frames present" but the frame count is cut off after 2 of its 4 bytes: 0x0102_0000 frames.
        let header = [0xff, 0xfb, 0x90, 0xc0];
        let bytes = cat(&[&header, &[0; 17], &ascii("Xing"), &1u32.to_be_bytes(), &[1, 2]]);
        near(parse_duration_seconds(&bytes, "x.mp3", 1000), 0x0102_0000u32 as f64 * 1152.0 / 44100.0, 1e-6);
    }
